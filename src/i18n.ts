const dict: Record<LangCode, Record<keyof typeof zh, string>> = {
  'zh-CN': zh,
  en,
  ja,
  ru,
  ko,
  es,
  fr,
}

export type I18nKey = keyof typeof zh

function detectLang(): LangCode {
  const lang = (navigator.language || 'zh-CN').toLowerCase()
  if (lang.startsWith('zh')) return 'zh-CN'
  if (lang.startsWith('ja')) return 'ja'
  if (lang.startsWith('ru')) return 'ru'
  if (lang.startsWith('ko')) return 'ko'
  if (lang.startsWith('es')) return 'es'
  if (lang.startsWith('fr')) return 'fr'
  return 'en'
}

export const uiLang = ref<LangCode>(detectLang())

export function setUiLang(code: LangCode) {
  uiLang.value = code
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  const lang = uiLang.value
  let text = dict[lang][key] ?? dict['zh-CN'][key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  return text
}

export function formatError(err: unknown): string {
  return typeof err === 'string' ? err : err instanceof Error ? err.message : String(err)
}

/** 把后端返回的错误码（ENCODING_UNMAPPABLE 等）翻译成当前语言消息 */
export function translateIoError(err: unknown): string {
  const raw = formatError(err)
  if (raw === UNMAPPABLE_CODE) return t('encodingUnmappable')
  if (raw === LOSSY_CODE) return t('lossySaveBlocked')
  if (raw === LARGE_FILE_EDITED_CODE) return t('largeFileEditedBlocked')
  if (raw === FULL_LOAD_TOO_LARGE_CODE) return t('fullLoadTooLarge')
  if (raw === NOT_TEXT_CODE) return t('notTextFile')
  return raw
}

/** muya 编辑器内核支持的语言（无对应语言时回退 en） */
export function muyaLocale(lang: LangCode): string {
  switch (lang) {
    case 'zh-CN':
      return 'zh-CN'
    case 'ja':
      return 'ja'
    case 'ko':
      return 'ko'
    case 'es':
      return 'es'
    case 'fr':
      return 'fr'
    default:
      return 'en'
  }
}
